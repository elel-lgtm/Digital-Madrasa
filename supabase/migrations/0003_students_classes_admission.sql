-- Digital Madrasa — 0003: students, teachers, classes and admission numbers
-- ============================================================================

create table public.classes (
  id          uuid primary key default gen_random_uuid(),
  madrasa_id  uuid not null references public.madrasas (id) on delete cascade,
  name        text not null check (length(btrim(name)) between 2 and 80),
  level       text not null,
  teacher_id  uuid,
  schedule    jsonb not null default '[]'::jsonb,
  capacity    int not null check (capacity between 1 and 200),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create table public.teachers (
  id             uuid primary key default gen_random_uuid(),
  profile_id     uuid not null references public.profiles (id) on delete cascade,
  madrasa_id     uuid not null references public.madrasas (id) on delete cascade,
  employee_no    text not null,
  specialisation text,
  qiraah_styles  public.qiraah_style[] not null default array['hafs']::public.qiraah_style[],
  is_owner       boolean not null default false,
  status         public.teacher_status not null default 'invited',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  deleted_at     timestamptz,
  unique (madrasa_id, employee_no),
  unique (madrasa_id, profile_id)
);

alter table public.classes
  add constraint classes_teacher_fk
  foreign key (teacher_id) references public.teachers (id) on delete set null;

-- ------------------------------------------------------ admission counter --
-- The sequence is platform-wide per year, not per madrasa: parents link by
-- admission number alone, so DM-2026-0007 must identify exactly one student
-- across the entire platform.

create table public.admission_counters (
  admission_year int primary key,
  last_seq       int not null default 0 check (last_seq >= 0)
);

create table public.students (
  id                uuid primary key default gen_random_uuid(),
  profile_id        uuid not null references public.profiles (id) on delete cascade,
  madrasa_id        uuid not null references public.madrasas (id) on delete cascade,
  -- System-generated. The client has no way to supply this; see the trigger.
  admission_no      text not null unique,
  admission_year    int not null,
  date_of_birth     date not null check (date_of_birth > '1950-01-01'
                                          and date_of_birth < current_date),
  gender            text not null check (gender in ('male', 'female')),
  guardian_notes    text,
  class_id          uuid references public.classes (id) on delete set null,
  enrollment_status public.enrollment_status not null default 'active',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  deleted_at        timestamptz,
  constraint admission_no_format check (admission_no ~ '^DM-\d{4}-\d{4}$')
);

create table public.enrollments (
  id         uuid primary key default gen_random_uuid(),
  class_id   uuid not null references public.classes (id) on delete cascade,
  student_id uuid not null references public.students (id) on delete cascade,
  madrasa_id uuid not null references public.madrasas (id) on delete cascade,
  joined_at  timestamptz not null default now(),
  status     text not null default 'active',
  deleted_at timestamptz,
  unique (class_id, student_id)
);

create index classes_madrasa_idx   on public.classes (madrasa_id, created_at desc)
  where deleted_at is null;
create index classes_teacher_idx   on public.classes (teacher_id);
create index teachers_madrasa_idx  on public.teachers (madrasa_id) where deleted_at is null;
create index teachers_profile_idx  on public.teachers (profile_id);
create index students_madrasa_idx  on public.students (madrasa_id, created_at desc)
  where deleted_at is null;
create index students_class_idx    on public.students (class_id) where deleted_at is null;
create index students_profile_idx  on public.students (profile_id);
create index enrollments_class_idx on public.enrollments (class_id);
create index enrollments_student_idx on public.enrollments (student_id);

create trigger trg_classes_updated_at  before update on public.classes
  for each row execute function public.set_updated_at();
create trigger trg_teachers_updated_at before update on public.teachers
  for each row execute function public.set_updated_at();
create trigger trg_students_updated_at before update on public.students
  for each row execute function public.set_updated_at();

-- -------------------------------------------- admission number generation --
-- Generated by a BEFORE INSERT trigger rather than in the client or an Edge
-- Function, which makes it impossible to bypass. Concurrency-safe: the
-- upsert takes a row lock on the counter for the year.

create or replace function public.generate_admission_no()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_year int;
  v_seq  int;
begin
  if new.admission_no is not null then
    raise exception 'admission_no is system-generated and cannot be supplied';
  end if;

  v_year := coalesce(new.admission_year, extract(year from now())::int);

  insert into public.admission_counters (admission_year, last_seq)
  values (v_year, 1)
  on conflict (admission_year)
    do update set last_seq = public.admission_counters.last_seq + 1
  returning last_seq into v_seq;

  if v_seq > 9999 then
    -- Four digits caps us at 9,999 students per year platform-wide. The
    -- widening path is documented in the README; failing loudly beats
    -- silently minting a malformed number.
    raise exception 'admission sequence exhausted for year %', v_year;
  end if;

  new.admission_year := v_year;
  new.admission_no   := 'DM-' || v_year::text || '-' || lpad(v_seq::text, 4, '0');
  return new;
end;
$$;

create trigger trg_students_admission_no
  before insert on public.students
  for each row execute function public.generate_admission_no();

-- Nobody may rewrite an issued admission number: parents have it written down.
create or replace function public.freeze_admission_no()
returns trigger
language plpgsql
as $$
begin
  if new.admission_no is distinct from old.admission_no then
    raise exception 'admission_no is immutable once issued';
  end if;
  return new;
end;
$$;

create trigger trg_students_freeze_admission_no
  before update on public.students
  for each row execute function public.freeze_admission_no();
