-- Verifies the two guarantees the spec marks NON-NEGOTIABLE, against the
-- live schema. Everything happens inside a transaction that rolls back, so
-- running this leaves no rows behind and is safe against a real database.
--
--   node scripts/db-run.mjs supabase/tests/verify_core_guarantees.sql

begin;

do $$
declare
  v_madrasa uuid := gen_random_uuid();
  v_owner   uuid := gen_random_uuid();
  v_pupil   uuid := gen_random_uuid();
  v_admission text;
  v_year int := extract(year from now())::int;
  v_failed text[] := '{}';
begin
  -- Minimal fixtures. auth.users rows are required by the profiles FK.
  insert into auth.users (id, instance_id, aud, role, email, encrypted_password,
                          email_confirmed_at, created_at, updated_at)
  values (v_owner, '00000000-0000-0000-0000-000000000000', 'authenticated',
          'authenticated', 'verify-owner@example.test', '', now(), now(), now()),
         (v_pupil, '00000000-0000-0000-0000-000000000000', 'authenticated',
          'authenticated', 'verify-pupil@example.test', '', now(), now(), now());

  -- profiles.madrasa_id and madrasas.owner_id reference each other, so the
  -- profiles land first without a tenant and are attached afterwards. This is
  -- the same order the real signup Edge Function has to use.
  insert into public.profiles (id, role, madrasa_id, full_name, email)
  values (v_owner, 'teacher', null, 'Verify Owner', 'verify-owner@example.test'),
         (v_pupil, 'student', null, 'Verify Pupil', 'verify-pupil@example.test');

  insert into public.madrasas (id, name, slug, county, town, owner_id,
                               contact_email, contact_phone, status)
  values (v_madrasa, 'Verify Madrasa', 'verify-madrasa-' || substr(v_madrasa::text, 1, 8),
          'Mandera', 'Mandera Town', v_owner,
          'verify-owner@example.test', '+254712000000', 'active');

  update public.profiles set madrasa_id = v_madrasa where id in (v_owner, v_pupil);

  -- ---------------------------------------------------------------- test 1
  -- Admission number is generated by the trigger, in DM-YYYY-XXXX form.
  -- admission_no is NOT NULL with no default: proof the trigger supplies it.
  insert into public.students (profile_id, madrasa_id, admission_year,
                               date_of_birth, gender)
  values (v_pupil, v_madrasa, v_year, date '2014-03-01', 'male')
  returning admission_no into v_admission;

  if v_admission !~ ('^DM-' || v_year::text || '-\d{4}$') then
    v_failed := v_failed || ('admission_no format was ' || coalesce(v_admission, 'null'));
  else
    raise notice 'PASS  admission number generated: %', v_admission;
  end if;

  -- ---------------------------------------------------------------- test 2
  -- A client-supplied admission number must be rejected outright.
  begin
    insert into public.students (profile_id, madrasa_id, admission_no,
                                 admission_year, date_of_birth, gender)
    values (v_pupil, v_madrasa, 'DM-2026-9999', v_year, date '2014-03-01', 'male');
    v_failed := v_failed || 'client-supplied admission_no was ACCEPTED';
  exception
    when others then
      raise notice 'PASS  client-supplied admission_no rejected: %', sqlerrm;
  end;

  -- ---------------------------------------------------------------- test 3
  -- is_platform_admin defaults false and is never client-settable.
  if (select is_platform_admin from public.profiles where id = v_owner) is not false then
    v_failed := v_failed || 'is_platform_admin did not default to false';
  else
    raise notice 'PASS  is_platform_admin defaults to false';
  end if;

  -- ---------------------------------------------------------------- test 4
  -- Self-escalation blocked for an authenticated principal. The policy's
  -- WITH CHECK compares the new row against the caller's current values.
  set local role authenticated;
  perform set_config('request.jwt.claims',
                     json_build_object('sub', v_owner::text, 'role', 'authenticated')::text,
                     true);

  -- Guard the harness itself. `postgres` has BYPASSRLS, so if the role switch
  -- silently failed this test would pass while proving nothing at all.
  if current_user <> 'authenticated' then
    raise exception 'harness broken: expected role authenticated, got %', current_user;
  end if;
  if auth.uid() is distinct from v_owner then
    raise exception 'harness broken: auth.uid() is %, expected %', auth.uid(), v_owner;
  end if;
  raise notice 'harness ok: acting as % with auth.uid() = %', current_user, auth.uid();

  begin
    update public.profiles set is_platform_admin = true where id = v_owner;
    if found then
      v_failed := v_failed || 'SELF-ESCALATION SUCCEEDED — user set own is_platform_admin';
    else
      raise notice 'PASS  self-escalation blocked (no row updated)';
    end if;
  exception
    when insufficient_privilege or check_violation then
      raise notice 'PASS  self-escalation blocked by policy: %', sqlerrm;
  end;

  reset role;

  -- ---------------------------------------------------------------- verdict
  if array_length(v_failed, 1) > 0 then
    raise exception E'\n\nFAILURES:\n  - %\n', array_to_string(v_failed, E'\n  - ');
  end if;

  raise notice E'\nAll core guarantees hold.';
end $$;

rollback;
